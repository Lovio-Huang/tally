#!/bin/sh
# Regenerates requirements-dev.txt: the dev tools pyproject.toml lists and everything they
# pull in, resolved in a clean python:3.14-slim container (the image's Python) on top of
# the runtime pins in requirements.txt. Run it after changing the dev tools in
# pyproject.toml; Dependabot keeps the pins current otherwise.
set -eu
cd "$(dirname "$0")/.."
pins=$(docker run --rm -v "$PWD:/src:ro" -w /src python:3.14-slim sh -c '
  python -m venv /tmp/v >/dev/null
  dev=$(python -c "import tomllib; print(*tomllib.load(open(\"pyproject.toml\", \"rb\"))[\"project\"][\"optional-dependencies\"][\"dev\"])")
  /tmp/v/bin/pip install -q --disable-pip-version-check -r requirements.txt $dev
  # --exclude matches normalized names, so prometheus_client == prometheus-client
  /tmp/v/bin/pip freeze $(sed -n "s/^\([A-Za-z0-9._-]*\)==.*/--exclude \1/p" requirements.txt)
')
cat > requirements-dev.txt <<HEADER
# Exact versions of everything tests, lint and coverage need: the runtime pins
# (requirements.txt) plus the dev tools and all of their dependencies. CI installs from
# here, so a run next month uses what passed today; pyproject.toml keeps the ranges.
#   pip install -r requirements-dev.txt && pip install --no-deps -e . && pip check
# Generated by scripts/lock-dev.sh; Dependabot updates the pins with requirements.txt.
-r requirements.txt
$pins
HEADER
echo "requirements-dev.txt: $(echo "$pins" | wc -l | tr -d ' ') dev pins"
